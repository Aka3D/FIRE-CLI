function Assert-FirePgDiffImage {
    $images = @(Get-FireLocalImages 'fire/pg-schema-diff' '\d+\.\d+\.\d+')
    if ($images.Count) { $Script:PgDiffImage = $images[0]; return }
    Install-FirePgDiffImage
}

function Get-FireNormalizedPgSchema {
    param([string]$Container, [string]$User, [string]$Password, [string]$Database)

    $dump = Invoke-FireNative docker @('exec', '-e', "PGPASSWORD=$Password", $Container, 'pg_dump',
        '--schema-only', '--no-owner', '--no-acl', '--exclude-table=public.flyway_schema_history',
        '-U', $User, '-d', $Database)
    return (@($dump -split '\r?\n' | Where-Object {
        $_.Trim() -and -not $_.StartsWith('--') -and $_ -notmatch '^\\(?:restrict|unrestrict)'
    } | ForEach-Object { $_.TrimEnd() }) -join "`n")
}

function Test-FirePostgresSchemaEqual {
    param($Project, $Credentials, [string]$Expected, [string]$Actual)

    $left = Get-FireNormalizedPgSchema $Project.Container 'postgres' $Credentials.password $Expected
    $right = Get-FireNormalizedPgSchema $Project.Container 'postgres' $Credentials.password $Actual
    return $left -ceq $right
}

function Invoke-FirePgDiff {
    param($Project, $Credentials, [string]$From, [string]$To)

    Assert-FirePgDiffImage
    $fromDsn = "postgres://postgres@localhost:5432/$From`?sslmode=disable"
    $toDsn = "postgres://postgres@localhost:5432/$To`?sslmode=disable"
    return Invoke-FireNative docker @('run', '--rm', '--network', "container:$($Project.Container)",
        '--env', "PGPASSWORD=$($Credentials.password)", $Script:PgDiffImage, 'plan',
        '--from-dsn', $fromDsn, '--to-dsn', $toDsn, '--output-format', 'sql', '--no-concurrent-index-ops', '--data-pack-new-tables=false')
}

function Backup-FirePostgres {
    param($Project, $Credentials, [string]$Database, [string]$TargetPath)

    $containerPath = "/tmp/fire_$([Guid]::NewGuid().ToString('N')).dump"
    try {
        Invoke-FireNative docker @('exec', '-e', "PGPASSWORD=$($Credentials.password)", $Project.Container,
            'pg_dump', '-Fc', '--no-owner', '--no-acl', '-U', 'postgres', '-d', $Database, '-f', $containerPath) | Out-Null
        Invoke-FireNative docker @('cp', "$($Project.Container):$containerPath", $TargetPath) | Out-Null
    }
    finally { Invoke-FireNative docker @('exec', $Project.Container, 'rm', '-f', $containerPath) -AllowFailure | Out-Null }
}

function Restore-FirePostgres {
    param($Project, $Credentials, [string]$Database, [string]$SourcePath, [string]$Activity)

    $containerPath = "/tmp/fire_$([Guid]::NewGuid().ToString('N')).dump"
    Invoke-FireNative docker @('cp', $SourcePath, "$($Project.Container):$containerPath") | Out-Null
    try {
        New-FireDatabase $Project $Credentials $Database
        Invoke-FireNative docker @('exec', '-e', "PGPASSWORD=$($Credentials.password)", $Project.Container,
            'pg_restore', '--exit-on-error', '--no-owner', '--no-acl', '-U', 'postgres', '-d', $Database, $containerPath) -Activity $Activity | Out-Null
    }
    finally { Invoke-FireNative docker @('exec', $Project.Container, 'rm', '-f', $containerPath) -AllowFailure | Out-Null }
}

